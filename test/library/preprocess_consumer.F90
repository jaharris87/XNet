Program preprocess_consumer
  ! Each input directory is a private copy of the public ASCII network, never a shared symlink.
  Use xnet_api, Only: dp, xnet_controls_t, xnet_network_t, xnet_timing_t, &
    & set_xnet_controls_defaults, xnet_initialize, xnet_burn_batch, xnet_finalize, &
    & xnet_success, xnet_invalid, xnet_lifecycle_error
  Use consumer_fixture, Only: fixture_state, check
  Implicit None
  Type(xnet_controls_t) :: controls
  Type(xnet_network_t) :: network, duplicate
  Type(xnet_timing_t) :: timing
  Character(80) :: data_dir, bad_dir, filename
  Character(512) :: message
  Character :: first_byte, marker
  Integer :: ierr, iteration, missing, unit, ids(3,1), counters(5,1), steps, species(3)
  Real(dp) :: density(1), temperature(1), ye(1), restart(1), loss(1), aux_x(1), aux_a(1), aux_z(1)
  Real(dp), Allocatable :: x(:,:)
  Logical :: exists

  Call set_xnet_controls_defaults(controls)
  controls%nzbatchmx = 1
  controls%idiag = -2
  controls%t9nse = 11.0_dp
  If ( Command_Argument_Count() == 2 ) Then
    Call Get_Command_Argument(1,data_dir)
    controls%data_dir = data_dir
    controls%iprocess = 0
    Call xnet_initialize(controls,network,ierr,message)
    Call check(ierr == xnet_success,'load-only prepared network')
    Call xnet_finalize(ierr,message)
    Call check(ierr == xnet_success,'load-only finalization')
    Stop
  EndIf
  Call check(Command_Argument_Count() == 5,'expected two network copies and three missing-ASCII directories')
  Call Get_Command_Argument(1,data_dir)
  controls%data_dir = data_dir
  controls%iprocess = 0
  Call xnet_initialize(controls,network,ierr,message)
  Call check(ierr == xnet_invalid .and. Index(message,'nets3') > 0,'missing generated files are checked with iprocess=0')
  Do missing = 1, 3
    Call Get_Command_Argument(missing+2,bad_dir)
    controls%data_dir = bad_dir
    controls%iprocess = 1
    Call xnet_initialize(controls,network,ierr,message)
    Call check(ierr == xnet_invalid,'missing ASCII source returns checked invalid status')
    Inquire(file=Trim(bad_dir)//'/nets3',exist=exists)
    Call check(.not. exists,'ASCII preflight creates no generated output')
  EndDo

  ! Repeat the first network and then change its size in the same process.
  Do iteration = 1, 3
    Call Get_Command_Argument(Merge(1,2,iteration < 3),data_dir)
    controls%data_dir = data_dir
    controls%iprocess = 1
    Call xnet_initialize(controls,network,ierr,message)
    If ( ierr /= xnet_success ) Write(*,'(a)') Trim(message)
    Call check(ierr == xnet_success,'runtime preprocessing initialization')
    species(iteration) = Size(network%names)
    Do missing = 1, Size(network%names)
      Write(*,'(a,1x,i0,1x,a,2(1x,i0),2(1x,es26.17e3))') 'PREPROCESS_META',iteration, &
        & Trim(Adjustl(network%names(missing))),network%mass_number(missing),network%charge_number(missing), &
        & network%binding_energy_mev(missing),network%mass_excess_mev(missing)
    EndDo

    ! A duplicate initialization must reject before regeneration, even if a generated byte changed.
    filename = Trim(data_dir)//'/nets3'
    Open(newunit=unit,file=Trim(filename),status='old',access='stream',form='unformatted',action='readwrite')
    Read(unit,pos=1) first_byte
    marker = Achar(Ieor(Iachar(first_byte),1))
    Write(unit,pos=1) marker
    Close(unit)
    Call xnet_initialize(controls,duplicate,ierr,message)
    Call check(ierr == xnet_lifecycle_error,'duplicate initialization rejected')
    Open(newunit=unit,file=Trim(filename),status='old',access='stream',form='unformatted',action='readwrite')
    Read(unit,pos=1) marker
    Call check(marker /= first_byte,'duplicate initialization did not regenerate network')
    Write(unit,pos=1) first_byte
    Close(unit)

    Allocate(x(Size(network%names),1))
    Call fixture_state(network%names,density,temperature,ye,x,restart,aux_x,aux_a,aux_z)
    ids(:,1) = [iteration,-7,42]
    Call xnet_burn_batch(0.01_dp,[.true.],ids,density,temperature,ye,x,restart,loss,counters,timing, &
      & ierr,message,aux_x,aux_a,aux_z,steps)
    Call check(ierr == xnet_success .and. steps > 0,'burn after runtime preprocessing')
    Call check(All(counters(:,1) > 0),'runtime-preprocessed network performs real integration')
    Deallocate(x)
    Call xnet_finalize(ierr,message)
    Call check(ierr == xnet_success,'finalize runtime-preprocessed network')
    Call xnet_finalize(ierr,message)
    Call check(ierr == xnet_success,'repeat finalize runtime-preprocessed network')

    ! Prepared data must initialize without preprocessing or changing generated output bytes.
    controls%iprocess = 0
    Call xnet_initialize(controls,network,ierr,message)
    Call check(ierr == xnet_success,'load prepared network with iprocess=0')
    Call xnet_finalize(ierr,message)
    Call check(ierr == xnet_success,'finalize prepared network')
  EndDo
  Call check(species(1) == species(2) .and. species(1) /= species(3),'same and differently sized network lifetimes')
  Write(*,'(a)') 'PREPROCESS_CHECKS_PASSED'
End Program preprocess_consumer
